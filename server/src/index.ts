import { config } from './config.js';
import { LowerThirds } from './services/lowerthirds.js';
import { Show } from './services/show.js';
import { openDb } from './db/db.js';
import { buildApp } from './app.js';
import { SyncService } from './services/sync.js';
import { WorkbookWriter } from './services/workbook.js';
import { tidyAssetsFolder } from './services/assets.js';
import { applyGoldCupOnStart } from './services/presets.js';
import { GeneratorExporter, seedGenerator } from './services/generator/generator.js';
import { applyTeamGraphicsOnStart } from './services/teamGraphics.js';
import { roundStoredFlagsOnStart } from './services/flags.js';
import { rankingOnStart } from './services/ranking.js';
import { MatchboardExporter, seedHighlightTemplate } from './services/matchboard/matchboard.js';
import { createTemplate } from './services/generator/generator.js';

const db = openDb(config.dbPath);
const sync = new SyncService(db);
const workbook = new WorkbookWriter({ db, assetsDir: config.assetsDir }, config.workbookFile, (m) => app.log.warn(m));
const generator = new GeneratorExporter({ db, assetsDir: config.assetsDir }, (m) => app.log.warn(m));
const matchboard = new MatchboardExporter({ db, assetsDir: config.assetsDir }, (m) => app.log.warn(m));
const lowerThirds = new LowerThirds({ db, assetsDir: config.assetsDir }, undefined, (m) => console.warn(m));
const show = new Show({ db, assetsDir: config.assetsDir }, lowerThirds, undefined, (m) => console.warn(m));
const app = await buildApp({ db, generator, matchboard, lowerThirds, show, assetsDir: config.assetsDir, sync, workbook, webDist: config.webDist, dbPath: config.dbPath, maxUploadBytes: config.maxUploadBytes, password: config.password });

const preset = applyGoldCupOnStart({ db, assetsDir: config.assetsDir });
if (preset) app.log.info(`SSL Gold Cup data applied: ${JSON.stringify(preset)}`);
seedGenerator(db);
seedHighlightTemplate(db, (t) => createTemplate(db, t));
const graphics = applyTeamGraphicsOnStart({ db, assetsDir: config.assetsDir });
if (graphics) app.log.info(`Team flags and emblems applied: ${JSON.stringify(graphics)}`);
const rounded = roundStoredFlagsOnStart({ db, assetsDir: config.assetsDir });
if (rounded) app.log.info(`Flags rounded: ${rounded}`);
sync.start();
const stopRanking = rankingOnStart(db, (m) => app.log.info(m));
tidyAssetsFolder({ db, assetsDir: config.assetsDir });
workbook.start();
generator.start();
lowerThirds.start();
show.start();
matchboard.schedule(2000);
await app.listen({ host: config.host, port: config.port });
app.log.info(`Database: ${config.dbPath}`);
app.log.info(`Assets folder: ${config.assetsDir}`);
app.log.info(`Workbook for vMix: ${config.workbookFile}`);
app.log.info(`Generated PNGs: ${generator.dir}`);
app.log.info(`Dashboard: http://${config.host === '0.0.0.0' ? 'localhost' : config.host}:${config.port}`);

const shutdown = async () => {
  sync.stop();
  stopRanking();
  workbook.stop();
  generator.stop();
  matchboard.stop();
  await app.close();
  db.close();
  process.exit(0);
};
process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
